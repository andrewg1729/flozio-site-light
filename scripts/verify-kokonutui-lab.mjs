import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, ".component-lab-cache/kokonutui-source");
const require = createRequire(path.join(source, "package.json"));
const { chromium } = require("playwright-core");
const browser = await chromium.launch({ headless: true, executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", args: ["--disable-gpu", "--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (error) => errors.push(String(error.message || error)));
const response = await page.goto("http://localhost:38474/lab", { waitUntil: "domcontentloaded", timeout: 30000 });
await page.waitForTimeout(500);
const counts = await page.locator("main").innerText();
if (!counts.includes("80 of 80 free components") || !counts.includes("80 fully reviewed")) throw new Error(`Unexpected completion count or stale catalog. Lab text: ${counts.slice(0, 500)}`);
const cards = page.locator("main > ul > li");
if (await cards.count() !== 80) throw new Error(`Expected 80 catalog entries, found ${await cards.count()}.`);
const input = page.getByRole("searchbox", { name: "Search Kokonut UI components" });
await input.fill("conversation-intelligence");
if (await cards.count() !== 1) throw new Error(`Expected one conversation-intelligence search result, found ${await cards.count()}.`);
const resultText = await cards.first().innerText();
if (!resultText.includes("Synced Transcript") || !resultText.includes("Flozio fit") || !resultText.includes("Observed motion") || !resultText.includes("call-review")) throw new Error("Search result omitted the description, observed motion, fit, or fit tag.");
const evidence = path.join(source, "research/evidence");
await page.screenshot({ path: path.join(evidence, "lab-search-desktop.png"), fullPage: false });
await page.setViewportSize({ width: 390, height: 844 });
const width = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, body: document.body.scrollWidth }));
if (width.document > width.viewport || width.body > width.viewport) throw new Error(`Mobile lab overflows: ${JSON.stringify(width)}`);
await page.screenshot({ path: path.join(evidence, "lab-search-mobile.png"), fullPage: false });
if (response?.status() !== 200 || errors.length) throw new Error(`Lab verification failed: status=${response?.status()}, errors=${errors.join("; ")}`);
console.log(`Kokonut lab verified: HTTP ${response.status()}, 80/80 reviewed records, searchable motion/Flozio tags, 390px without overflow, no page errors.`);
await browser.close();
